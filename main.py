# Text Game

# What is a scene?
# A scene is a section of your story with choices and outcomes.
# A scene describes what is happeing and asks the player what they
# want to do next.

# How do choices shape the game?
# Choices let the player change what happens next.
# We take take the player's choice using the input() function and then use if statements to determine what happens next.
# we navigate the story using if/else.

# How do we plan a scene?
# 1. Describe the scene
# What does the player see or experience?
# set the scene in words so the player understand where they are.

# 2. Present the player with choices
# what options can the player pick?
# keep them clear and engaging.

# 3. Determine the outcomes of each choice
# what happens inmediately after the player makes a choice?
# "narrative response to the choice"

# 4. Consequences of the choice
# What changes in the game's state?
# health, items, or other variables that persist for future scenes.

